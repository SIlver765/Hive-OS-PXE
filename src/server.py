def build_apkovl():
    """Alpine overlay that runs flash.sh at boot. Built once per start."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        def add(name, data, mode=0o644):
            ti = tarfile.TarInfo(name); ti.size = len(data); ti.mode = mode; ti.mtime = int(time.time())
            t.addfile(ti, io.BytesIO(data))
        def link(name, target):
            ti = tarfile.TarInfo(name); ti.type = tarfile.SYMTYPE; ti.linkname = target; t.addfile(ti)
        with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "scripts", "flash.sh"), "rb") as f:
            add("etc/local.d/hive-flash.start", f.read(), 0o755)
        add("etc/network/interfaces", b"auto lo\niface lo inet loopback\nauto eth0\niface eth0 inet dhcp\n")
        add("etc/apk/world", b"alpine-base\n")
        link("etc/runlevels/boot/networking", "/etc/init.d/networking")
        link("etc/runlevels/default/local", "/etc/init.d/local")
    return buf.getvalue()

