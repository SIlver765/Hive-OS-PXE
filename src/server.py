# ---------- network detection ----------
def detect_net():
    """Return (ip, iface) of the default-route interface."""
    ip = iface = ""
    try:
        out = subprocess.run(["ip", "-4", "route", "get", "1.1.1.1"], capture_output=True, text=True, timeout=5).stdout
        m = re.search(r"dev (\S+)", out); iface = m.group(1) if m else ""
        m = re.search(r"src (\S+)", out); ip = m.group(1) if m else ""
    except Exception: pass
    if not ip:
        try:
            s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM); s.connect(("1.1.1.1", 53))
            ip = s.getsockname()[0]; s.close()
        except Exception: ip = "127.0.0.1"
    return ip, iface

def server_ip():
    return cfg.get("server_ip") or os.environ.get("SERVER_IP") or detect_net()[0]


# ---------- dnsmasq ----------
def write_dnsmasq():
    ip, iface = detect_net()
    ip = cfg.get("server_ip") or os.environ.get("SERVER_IP") or ip
    conf = f"""# generated by server.py -- do not edit
port=0
{f'interface={iface}' if iface else ''}
bind-interfaces
log-dhcp
dhcp-range={ip},proxy
enable-tftp
tftp-root={TFTP}
dhcp-match=set:ipxe,175
pxe-service=tag:!ipxe,x86PC,"Hive OS Deploy (BIOS)",undionly.kpxe
pxe-service=tag:!ipxe,BC_EFI,"Hive OS Deploy (UEFI)",ipxe.efi
pxe-service=tag:!ipxe,X86-64_EFI,"Hive OS Deploy (UEFI)",ipxe.efi
pxe-service=tag:ipxe,x86PC,"Hive OS Deploy",boot.ipxe
pxe-service=tag:ipxe,BC_EFI,"Hive OS Deploy",boot.ipxe
pxe-service=tag:ipxe,X86-64_EFI,"Hive OS Deploy",boot.ipxe
"""
    os.makedirs(TFTP, exist_ok=True)
    with open(os.path.join(TFTP, "boot.ipxe"), "w") as f:  # tiny stub: hand over to the dynamic HTTP script
        f.write(f"#!ipxe\nchain http://{ip}:{PUBLIC_PORT}/boot.ipxe?mac=${{net0/mac}} || exit\n")
    path = os.path.join(tempfile.gettempdir(), "dnsmasq.conf")
    with open(path, "w") as f: f.write(conf)
    return path

def run_dnsmasq():
    global dnsmasq_proc
    with lock:
        if dnsmasq_proc and dnsmasq_proc.poll() is None:
            dnsmasq_proc.terminate(); dnsmasq_proc.wait(5)
        path = write_dnsmasq()
        try:
            dnsmasq_proc = subprocess.Popen([DNSMASQ_BIN, "--keep-in-foreground", "--log-facility=-", f"--conf-file={path}"],
                                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        except FileNotFoundError:
            log_lines.append(f"{now()} dnsmasq binary not found"); return
    threading.Thread(target=pump, args=(dnsmasq_proc,), daemon=True).start()

def pump(p):
    for line in p.stdout:
        line = line.rstrip(); log_lines.append(line); print(line, flush=True)

def supervise():
    while True:
        time.sleep(10)
        if dnsmasq_proc is not None and dnsmasq_proc.poll() is not None:
            log_lines.append(f"{now()} dnsmasq exited ({dnsmasq_proc.returncode}), restarting"); run_dnsmasq()


